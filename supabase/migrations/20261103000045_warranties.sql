-- Garantia das obras (menu Execução › Garantias e aba Garantia da obra).
-- Uma garantia começa na entrega da obra (12 meses por padrão, cláusula do contrato) e guarda os
-- chamados do cliente (o que relatou, de qual etapa, quem executou, se é coberto) e as visitas de
-- cada chamado. Obras entregues antes da plataforma entram como garantia avulsa (sem obra): nome,
-- cliente, endereço e as datas de início e fim. Registros operacionais, sem valores: admin,
-- financeiro e equipe leem e escrevem, como as pendências; o custo de uma visita vai para o
-- Financeiro como conta a pagar ligada ao chamado (financial_entries.warranty_claim_id), então só
-- quem vê custos o vê.

CREATE TABLE public.warranties (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Obra da plataforma (uma garantia por obra) ou vazio para obra entregue antes da plataforma.
  work_id uuid UNIQUE REFERENCES public.work_registry(id) ON DELETE CASCADE,
  name text,
  client_id uuid REFERENCES public.people(id) ON DELETE SET NULL,
  address text,
  start_date date NOT NULL,
  end_date date NOT NULL,
  term_months int CHECK (term_months BETWEEN 1 AND 240),
  handover_path text,
  notes text,
  final_inspection_date date,
  final_inspection_done boolean NOT NULL DEFAULT false,
  created_by uuid, updated_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date > start_date),
  CHECK (work_id IS NOT NULL OR nullif(trim(coalesce(name,'')),'') IS NOT NULL)
);
CREATE INDEX warranties_end_idx ON public.warranties(end_date);
CREATE INDEX warranties_client_idx ON public.warranties(client_id);

CREATE TABLE public.warranty_claims (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Número do chamado (GAR-0001), único em toda a empresa.
  number int GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  warranty_id uuid NOT NULL REFERENCES public.warranties(id) ON DELETE CASCADE,
  reported_at date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')::date,
  channel text NOT NULL DEFAULT 'whatsapp'
    CHECK (channel IN ('whatsapp','telefone','email','visita','outro')),
  reported_by text,
  description text NOT NULL CHECK (nullif(trim(description),'') IS NOT NULL),
  -- Etapa do cadastro "Etapas da obra" (igual em todas as obras, para os relatórios) e,
  -- opcionalmente, a etapa da própria obra.
  stage_id uuid REFERENCES public.stages(id) ON DELETE SET NULL,
  work_stage_id uuid REFERENCES public.work_stages(id) ON DELETE SET NULL,
  executor_kind text NOT NULL DEFAULT 'equipe' CHECK (executor_kind IN ('equipe','prestador')),
  executor_id uuid REFERENCES public.people(id) ON DELETE SET NULL,
  evaluation text NOT NULL DEFAULT 'a_avaliar'
    CHECK (evaluation IN ('a_avaliar','procedente','mau_uso','desgaste','terceiros','preexistente','material_cliente')),
  -- Data da visita que resolveu (preenchida pelo banco a partir das visitas).
  resolved_at date,
  lesson text,
  photo_paths text[] NOT NULL DEFAULT '{}',
  created_by uuid, updated_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX warranty_claims_warranty_idx ON public.warranty_claims(warranty_id, reported_at);
CREATE INDEX warranty_claims_stage_idx ON public.warranty_claims(stage_id);
CREATE INDEX warranty_claims_work_stage_idx ON public.warranty_claims(work_stage_id);
CREATE INDEX warranty_claims_executor_idx ON public.warranty_claims(executor_id);

CREATE TABLE public.warranty_visits (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  claim_id uuid NOT NULL REFERENCES public.warranty_claims(id) ON DELETE CASCADE,
  visit_date date NOT NULL,
  -- Agendada (false) ou feita (true); só a feita tem resultado.
  done boolean NOT NULL DEFAULT false,
  person_id uuid REFERENCES public.people(id) ON DELETE SET NULL,
  responsible text,
  outcome text CHECK (outcome IN ('avaliacao','reparo','voltar','resolvido')),
  notes text,
  photo_paths text[] NOT NULL DEFAULT '{}',
  created_by uuid, updated_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (done OR outcome IS NULL)
);
CREATE INDEX warranty_visits_claim_idx ON public.warranty_visits(claim_id, visit_date);
CREATE INDEX warranty_visits_date_idx ON public.warranty_visits(visit_date);
CREATE INDEX warranty_visits_person_idx ON public.warranty_visits(person_id);

