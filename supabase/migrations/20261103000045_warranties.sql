-- Garantia: não muda de obra; nome e endereço sem espaços sobrando.
CREATE FUNCTION public.guard_warranty() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 new.name := nullif(trim(coalesce(new.name,'')),'');
 new.address := nullif(trim(coalesce(new.address,'')),'');
 IF TG_OP='UPDATE' AND new.work_id IS DISTINCT FROM old.work_id THEN
   RAISE EXCEPTION 'A garantia não pode mudar de obra.';
 END IF;
 RETURN new;
END $$;
CREATE TRIGGER warranties_guard BEFORE INSERT OR UPDATE ON public.warranties
  FOR EACH ROW EXECUTE FUNCTION public.guard_warranty();

-- Chamado: não muda de garantia; a etapa da obra precisa ser da obra da garantia; a data em que
-- resolveu vem das visitas, nunca digitada.
CREATE FUNCTION public.guard_warranty_claim() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 new.description := trim(new.description);
 new.reported_by := nullif(trim(coalesce(new.reported_by,'')),'');
 IF TG_OP='UPDATE' AND new.warranty_id<>old.warranty_id THEN
   RAISE EXCEPTION 'O chamado não pode mudar de garantia.';
 END IF;
 IF new.work_stage_id IS NOT NULL AND NOT EXISTS(
   SELECT 1 FROM public.work_stages s JOIN public.warranties w ON w.work_id=s.work_id
    WHERE s.id=new.work_stage_id AND w.id=new.warranty_id) THEN
   RAISE EXCEPTION 'A etapa do chamado deve ser da obra da garantia.';
 END IF;
 IF TG_OP='INSERT' THEN
   new.resolved_at := NULL;
 ELSIF current_setting('jmg.warranty_sync', true) IS DISTINCT FROM 'on' THEN
   new.resolved_at := old.resolved_at;
 END IF;
 RETURN new;
END $$;
CREATE TRIGGER warranty_claims_guard BEFORE INSERT OR UPDATE ON public.warranty_claims
  FOR EACH ROW EXECUTE FUNCTION public.guard_warranty_claim();

-- Visita: não muda de chamado; ao salvar, o chamado fica resolvido na data da última visita
-- feita com resultado "resolvido" (ou volta a aberto se ela for desfeita).
CREATE FUNCTION public.guard_warranty_visit() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 new.responsible := nullif(trim(coalesce(new.responsible,'')),'');
 IF TG_OP='UPDATE' AND new.claim_id<>old.claim_id THEN
   RAISE EXCEPTION 'A visita não pode mudar de chamado.';
 END IF;
 IF NOT new.done THEN new.outcome := NULL; END IF;
 RETURN new;
END $$;
CREATE TRIGGER warranty_visits_guard BEFORE INSERT OR UPDATE ON public.warranty_visits
  FOR EACH ROW EXECUTE FUNCTION public.guard_warranty_visit();

CREATE FUNCTION public.sync_warranty_claim() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
DECLARE cid uuid := coalesce(new.claim_id, old.claim_id);
BEGIN
 PERFORM set_config('jmg.warranty_sync','on',true);
 UPDATE public.warranty_claims SET resolved_at = (
   SELECT max(visit_date) FROM public.warranty_visits
    WHERE claim_id=cid AND done AND outcome='resolvido')
  WHERE id=cid;
 PERFORM set_config('jmg.warranty_sync','off',true);
 RETURN coalesce(new, old);
END $$;
CREATE TRIGGER warranty_visits_sync AFTER INSERT OR UPDATE OR DELETE ON public.warranty_visits
  FOR EACH ROW EXECUTE FUNCTION public.sync_warranty_claim();

-- Auditoria em work_history (só garantias de obras da plataforma; a avulsa não tem obra).
CREATE FUNCTION public.log_warranty_change() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE wid uuid;
BEGIN
 IF TG_TABLE_NAME='warranties' THEN
   wid := coalesce(new.work_id, old.work_id);
 ELSIF TG_TABLE_NAME='warranty_claims' THEN
   SELECT work_id INTO wid FROM public.warranties WHERE id=coalesce(new.warranty_id, old.warranty_id);
 ELSE
   SELECT w.work_id INTO wid FROM public.warranty_claims c JOIN public.warranties w ON w.id=c.warranty_id
    WHERE c.id=coalesce(new.claim_id, old.claim_id);
 END IF;
 IF wid IS NOT NULL AND EXISTS(SELECT 1 FROM public.work_registry WHERE id=wid) THEN
   INSERT INTO public.work_history(work_id,entity,entity_id,before,after)
   VALUES(wid,TG_TABLE_NAME,coalesce(new.id,old.id),
     CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(old) END,
     CASE WHEN TG_OP='DELETE' THEN NULL ELSE to_jsonb(new) END);
 END IF;
 RETURN coalesce(new,old);
END $$;
REVOKE EXECUTE ON FUNCTION public.log_warranty_change() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER warranties_history AFTER INSERT OR UPDATE OR DELETE ON public.warranties
  FOR EACH ROW EXECUTE FUNCTION public.log_warranty_change();
CREATE TRIGGER warranty_claims_history AFTER INSERT OR UPDATE OR DELETE ON public.warranty_claims
  FOR EACH ROW EXECUTE FUNCTION public.log_warranty_change();
CREATE TRIGGER warranty_visits_history AFTER INSERT OR UPDATE OR DELETE ON public.warranty_visits
  FOR EACH ROW EXECUTE FUNCTION public.log_warranty_change();

-- A antiga aba "Assistência" vira a aba Garantia: cada registro de assistência passa a ser um
-- chamado da garantia da sua obra (criada com início na entrega, ou no primeiro registro, e 12
-- meses). Os registros originais continuam em work_records.
INSERT INTO public.warranties(work_id, start_date, end_date, term_months, notes)
SELECT w.id, d.start, (d.start + interval '12 months')::date, 12,
       'Criada a partir dos registros de assistência.'
  FROM public.work_registry w
  JOIN LATERAL (
    SELECT coalesce(w.actual_end, (SELECT min(r.record_date) FROM public.work_records r
                                    WHERE r.work_id=w.id AND r.kind='assistencia')) AS start
  ) d ON true
 WHERE EXISTS(SELECT 1 FROM public.work_records r WHERE r.work_id=w.id AND r.kind='assistencia')
   AND NOT EXISTS(SELECT 1 FROM public.warranties x WHERE x.work_id=w.id);

INSERT INTO public.warranty_claims(warranty_id, reported_at, channel, description, work_stage_id,
  evaluation, lesson, created_by, created_at)
SELECT g.id, r.record_date, 'outro',
       trim(both E'\n' FROM coalesce(r.title,'') || coalesce(E'\n' || nullif(r.body,''), '')),
       r.stage_id, 'procedente', nullif(r.next_steps,''), r.created_by, r.created_at
  FROM public.work_records r
  JOIN public.warranties g ON g.work_id=r.work_id
 WHERE r.kind='assistencia' AND nullif(trim(coalesce(r.title,'') || coalesce(r.body,'')),'') IS NOT NULL;

-- Registros antigos concluídos viram uma visita feita e resolvida na data do registro.
INSERT INTO public.warranty_visits(claim_id, visit_date, done, outcome, responsible, notes)
SELECT c.id, coalesce(r.due_date, r.record_date), true, 'resolvido', nullif(r.responsible,''),
       'Registro migrado da aba Assistência.'
  FROM public.warranty_claims c
  JOIN public.warranties g ON g.id=c.warranty_id
  JOIN public.work_records r ON r.work_id=g.work_id AND r.kind='assistencia'
   AND r.record_date=c.reported_at AND r.created_at=c.created_at
 WHERE r.status IN ('concluido','aceito');

